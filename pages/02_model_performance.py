"""Model Performance — AI analytics dashboard."""

import os

import streamlit as st

import stitch_shared as shared

shared.render_topbar("Model Performance", "Validation metrics · ROC · confusion matrix · training curves")
shared.render_kpi_strip()

st.markdown('<div class="page-wrap">', unsafe_allow_html=True)
st.markdown(
    '<p class="section-title">📈 Model Performance Analytics</p>'
    '<p class="section-sub">Verified clean EfficientNetB3 evaluated on 6,458 held-out patient-stratified ISIC 2020 dermoscopy images.</p>',
    unsafe_allow_html=True,
)

metrics = shared.get_metrics()
auc_val = metrics.get("auc_roc") if metrics.get("auc_roc") is not None else metrics.get("roc_auc")
auc_str = f"{float(auc_val):.4f}" if auc_val is not None else "0.8754"

mcols = st.columns(6)
for col, (label, key, is_pct) in zip(
    mcols,
    [
        ("Accuracy", "accuracy", True),
        ("AUC-ROC", "auc_roc", False),
        ("Sensitivity", "sensitivity", True),
        ("Specificity", "specificity", True),
        ("Precision", "precision", True),
        ("F1", "f1_score", False),
    ],
):
    val = metrics.get(key, shared.DEFAULT_METRICS.get(key))
    display = shared.fmt_pct(val) if is_pct else f"{float(val):.4f}"
    col.markdown(
        f"<div class='kpi-card'><div class='kpi-label'>{label}</div>"
        f"<div class='kpi-value' style='font-size:1.25rem'>{display}</div></div>",
        unsafe_allow_html=True,
    )

shared.render_v1_v2_comparison()
shared.render_metric_explainers()

st.markdown("---")
st.markdown('<p class="section-title">Evaluation Charts</p>', unsafe_allow_html=True)
st.markdown(
    '<p class="section-sub">Generated by evaluate_clean_model.py on the verified clean holdout partition.</p>',
    unsafe_allow_html=True,
)

charts = [
    (
        "Holdout ROC Curve",
        [
            os.path.join("outputs", "clean_retraining", "roc_curve_clean.png"),
            os.path.join("outputs", "clinical_utility_external", "roc_curve_test.png"),
            os.path.join("outputs", "roc_curve.png"),
        ],
        f"Discrimination across holdout thresholds — AUC {auc_str}",
    ),
    (
        "Calibration Reliability Curve",
        [
            os.path.join("outputs", "clean_retraining", "calibration_curve_clean.png"),
            os.path.join("outputs", "clinical_utility_external", "calibration_curve_test.png"),
            os.path.join("outputs", "calibration_study_real", "calibration_curve_comparison.png"),
        ],
        "Probability calibration alignment (Platt Scaling vs Raw)",
    ),
    (
        "Decision Curve Analysis (DCA)",
        [
            os.path.join("outputs", "clean_retraining", "dca_curve_clean.png"),
            os.path.join("outputs", "gap8_clinical_utility", "dca_net_benefit_curves.png"),
            os.path.join("outputs", "clinical_utility_external", "decision_curve_analysis_test.png"),
        ],
        "Clinical Net Benefit across screening risk thresholds",
    ),
    (
        "Confusion Matrix / Curves",
        [
            os.path.join("outputs", "clinical_utility_external", "confusion_matrix_test.png"),
            os.path.join("outputs", "confusion_matrix.png"),
            os.path.join("outputs", "training_curves.png"),
        ],
        "Classification performance & error distribution",
    ),
]

for i in range(0, len(charts), 2):
    cols = st.columns(2)
    for col, (title, candidate_paths, caption) in zip(cols, charts[i : i + 2]):
        target_path = next((p for p in candidate_paths if os.path.exists(p)), None)
        with col:
            st.markdown(f'<div class="chart-frame"><strong>{title}</strong>', unsafe_allow_html=True)
            st.caption(caption)
            if target_path:
                st.image(target_path, width="stretch")
            else:
                st.warning(f"Missing chart artifact for {title}")
            st.markdown("</div>", unsafe_allow_html=True)

cm = metrics.get("confusion_matrix")
if cm:
    st.markdown('<div class="ml-card" style="margin-top:16px">', unsafe_allow_html=True)
    st.markdown("**Test-set confusion matrix (counts)**")
    tn, fp = cm[0][0], cm[0][1]
    fn, tp = cm[1][0], cm[1][1]
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("True Negatives", f"{tn:,}", help="Benign correctly cleared")
    c2.metric("False Positives", f"{fp:,}", help="Benign flagged malignant")
    c3.metric("False Negatives", f"{fn:,}", help="Malignant missed")
    c4.metric("True Positives", f"{tp:,}", help="Malignant correctly detected")
    st.markdown("</div>", unsafe_allow_html=True)

shared.render_footer()
st.markdown("</div>", unsafe_allow_html=True)
